"""Generate shopping and administrator TypeScript types from the API contracts."""
import argparse
import inspect
import json
from pathlib import Path

from recarena_contracts.http import EnvironmentBindings
from recarena_contracts.layout import Presentation
from recarena_contracts.models import PolicyDefinition
from recarena_contracts import browser


def typescript(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'anyOf' in schema or 'oneOf' in schema:
        return '(' + ' | '.join(map(typescript, schema.get('anyOf', schema.get('oneOf')))) + ')'
    if 'enum' in schema:
        return ' | '.join(json.dumps(x) for x in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + typescript(schema['items']) + '>'
    if kind == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            return '{ ' + '; '.join(json.dumps(k) + ('' if k in required else '?') + ': ' + typescript(v)
                for k, v in schema['properties'].items()) + ('; [key: string]: unknown' if schema.get('additionalProperties') else '') + ' }'
        if 'patternProperties' in schema:
            return '{ [key: string]: ' + ' | '.join(typescript(value) for value in schema['patternProperties'].values()) + ' }'
        value = schema.get('additionalProperties', {})
        return '{ [key: string]: ' + (typescript(value) if isinstance(value, dict) else 'unknown') + ' }'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def render_types(classes, *, administrator=False):
    definitions = {}
    for cls in classes:
        schema = cls.model_json_schema(mode='serialization')
        definitions.update(schema.pop('$defs', {}))
        definitions[cls.__name__] = schema
    label = 'administrator DTOs.' if administrator else 'do not edit.'
    header = f'// Generated by contracts/generate_api_types.py; {label}\n'
    return header + '\n'.join(
        f'export type {name} = {typescript(schema)};'
        for name, schema in sorted(definitions.items())
    ) + '\n'


def generated_types():
    shopping = [cls for cls in vars(browser).values()
                if inspect.isclass(cls) and cls.__module__ == browser.__name__]
    return {
        'api.ts': render_types(shopping),
        'control.ts': render_types((Presentation, EnvironmentBindings, PolicyDefinition), administrator=True),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check existing files without writing')
    args = parser.parse_args(argv)
    destination = Path(__file__).resolve().parents[1] / 'frontend/generated'
    files = generated_types()
    for name, contents in files.items():
        path = destination / name
        if args.check:
            if not path.is_file() or path.read_text() != contents:
                raise SystemExit(f'API TypeScript types drifted: {path.name}; regenerate and review.')
        else:
            destination.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    print('API TypeScript types ' + ('verified' if args.check else 'generated'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
